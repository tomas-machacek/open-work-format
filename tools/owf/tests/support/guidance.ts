import assert from 'node:assert/strict';
import { readFileSync, statSync } from 'node:fs';
import { isAbsolute, join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Parser } from 'commonmark';
import { parseDocument } from 'yaml';

export const guideTopics = [
  'workspace',
  'actions',
  'blocking-and-dependencies',
  'views',
  'browser-board',
  'deletion',
] as const;

// Audit the actual initialized tree, not the source templates. CommonMark ignores
// illustrative links in fenced code and resolves reference-style links as well.
export function auditWorkspaceGuidance(root: string, version: string): void {
  const entry = readFileSync(join(root, 'AGENTS.md'));
  assert.ok(
    entry.byteLength <= 4096,
    `AGENTS.md: ${entry.byteLength} UTF-8 bytes exceeds 4096`,
  );
  assert.doesNotMatch(entry.toString('utf8'), /^---(?:\r?\n|$)/u);
  const topics = guideTopics.map((topic) => `_knowledge/owf/${topic}.md`);
  const indexes = [
    'index.md',
    '_knowledge/index.md',
    '_knowledge/owf/index.md',
  ];
  const graph = new Map<string, string[]>();
  for (const name of ['AGENTS.md', ...indexes, ...topics]) {
    let body = readFileSync(join(root, name), 'utf8');
    if (topics.includes(name)) {
      const envelope = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/u.exec(body);
      assert.ok(envelope, `${name}: missing Knowledge envelope`);
      const yaml = parseDocument(envelope[1]!, { uniqueKeys: true });
      assert.equal(yaml.errors.length + yaml.warnings.length, 0, name);
      const metadata: unknown = yaml.toJS();
      assert.ok(
        typeof metadata === 'object' &&
          metadata !== null &&
          !Array.isArray(metadata),
      );
      assert.ok(
        'type' in metadata && metadata.type === 'OWF Knowledge Document',
        name,
      );
      for (const field of ['title', 'description'] as const) {
        const value: unknown = Reflect.get(metadata, field);
        assert.ok(
          typeof value === 'string' && value.trim(),
          `${name}: ${field}`,
        );
      }
      body = body.slice(envelope[0].length);
      assert.ok(
        body.includes(`Generated by OWF tool ${version}.`),
        `${name}: tool version`,
      );
      assert.ok(
        body.includes('initialization snapshot') &&
          body.includes('not\nautomatically synchronized'),
        `${name}: snapshot`,
      );
    } else {
      assert.doesNotMatch(body, /^(?:\uFEFF)?---(?:\r?\n|$)/u, name);
    }
    const walker = new Parser().parse(body).walker();
    let event;
    let headings = 0;
    const links: string[] = [];
    while ((event = walker.next())) {
      if (!event.entering) continue;
      const node = event.node;
      if (node.type === 'heading' && node.level === 1) headings++;
      if (node.type !== 'link' || !node.destination) continue;
      const destination = node.destination;
      if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/iu.test(destination)) continue;
      // Resolve against physical files so excess parent segments cannot be
      // clamped to a fictitious web-origin root and mistaken for valid links.
      // A leading slash explicitly starts at the Workspace, not the disk root.
      const rooted = destination.startsWith('/');
      const url = new URL(
        rooted ? `.${destination}` : destination,
        pathToFileURL(join(root, rooted ? 'index.md' : name)),
      );
      const path = fileURLToPath(url);
      const local = relative(root, path);
      assert.ok(
        local !== '..' && !local.startsWith(`..${sep}`) && !isAbsolute(local),
        `${name}: local link outside Workspace ${destination}`,
      );
      const target = local.split(sep).join('/');
      assert.ok(
        statSync(path, { throwIfNoEntry: false })?.isFile(),
        `${name}: broken local link ${destination}`,
      );
      links.push(target);
    }
    assert.equal(headings, 1, `${name}: one H1`);
    if (indexes.includes(name))
      assert.ok(body.startsWith('# Index\n'), `${name}: navigation index`);
    graph.set(name, links);
  }
  const reachable = (start: string) => {
    const visited = new Set<string>();
    const pending = [start];
    while (pending.length) {
      const name = pending.pop()!;
      if (visited.has(name)) continue;
      visited.add(name);
      pending.push(...(graph.get(name) ?? []));
    }
    return visited;
  };
  for (const start of ['AGENTS.md', 'index.md'])
    for (const target of [...indexes, ...topics])
      assert.ok(
        reachable(start).has(target),
        `${target}: unreachable from ${start}`,
      );
  assert.ok(graph.get('index.md')?.includes('_knowledge/index.md'));
  assert.ok(
    graph.get('_knowledge/index.md')?.includes('_knowledge/owf/index.md'),
  );
}
